const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const os = require("node:os");
const { ProjectTarget, UnityTarget, Deployment, checkPath } = require("../scripts/protocol-tool/Deployment.cjs");

function fixture(callback) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "escape-proto-tool-"));
  try { callback(root); }
  finally {
    // 테스트가 만든 파일만 명시적으로 정리하고, 디렉터리는 비재귀 삭제합니다.
    function clear(folder) {
      for (const entry of fs.readdirSync(folder, { withFileTypes: true })) {
        const item = path.join(folder, entry.name);
        if (entry.isDirectory()) clear(item);
        else fs.unlinkSync(item);
      }
      fs.rmdirSync(folder);
    }
    clear(root);
  }
}

const verification = { contractHash: "contract", fingerprint: "verified", tools: { tsProto: "test" } };
const content = text => Buffer.from("// Code generated by protoc\n" + text);

test("미리보기는 쓰지 않고 배포는 meta와 비관리 파일을 보존하며 반복 시 동일하다", () => fixture(root => {
  fs.mkdirSync(path.join(root, "generated"));
  fs.writeFileSync(path.join(root, "generated/Test.cs.meta"), "guid: keep");
  fs.writeFileSync(path.join(root, "generated/MyFile.cs"), "user content");
  const target = new ProjectTarget("client", root, "generated", { "Test.cs": content("new") }, verification);
  const writes = target.plan();
  assert.equal(fs.existsSync(path.join(root, "generated/Test.cs")), false);
  new Deployment(path.join(root, "backups")).apply(writes);
  assert.equal(fs.readFileSync(path.join(root, "generated/Test.cs.meta"), "utf8"), "guid: keep");
  assert.equal(fs.readFileSync(path.join(root, "generated/MyFile.cs"), "utf8"), "user content");
  assert.equal(target.plan().every(write => !write.changed), true);
  const manifest = JSON.parse(fs.readFileSync(path.join(root, "generated/protocol.manifest.json")));
  assert.equal(manifest.contractHash, "contract");
}));

test("수동 변경·비관리 충돌·폐기 파일이 있으면 배포 계획을 거부한다", () => fixture(root => {
  const target = new ProjectTarget("server", root, "generated", { "Test.ts": content("old") }, verification);
  new Deployment(path.join(root, "backups")).apply(target.plan());
  fs.writeFileSync(path.join(root, "generated/Test.ts"), "manually edited");
  const next = new ProjectTarget("server", root, "generated", { "Test.ts": content("new") }, verification);
  assert.throws(() => next.plan(), /수동 변경/);
  const retired = new ProjectTarget("server", root, "generated", { "Other.ts": content("new") }, verification);
  assert.throws(() => retired.plan(), /폐기/);
  fs.writeFileSync(path.join(root, "generated/Other.ts"), "user file");
  const conflict = new ProjectTarget("server", root, "different", { "Test.ts": content("new") }, verification);
  fs.mkdirSync(path.join(root, "different"));
  fs.writeFileSync(path.join(root, "different/Test.ts"), "user file");
  assert.throws(() => conflict.plan(), /관리하지 않는/);
}));

test("계획 이후 파일 변경은 적용 전에 거부한다", () => fixture(root => {
  const target = new ProjectTarget("server", root, "generated", { "Test.ts": content("new") }, verification);
  const writes = target.plan();
  fs.mkdirSync(path.join(root, "generated"));
  fs.writeFileSync(path.join(root, "generated/Test.ts"), "external change");
  assert.throws(() => new Deployment(path.join(root, "backups")).apply(writes), /계획 이후/);
  assert.equal(fs.readFileSync(path.join(root, "generated/Test.ts"), "utf8"), "external change");
}));

test("중간 쓰기 실패 시 기존 파일을 되돌리고 백업을 보존한다", () => fixture(root => {
  const target = new ProjectTarget("server", root, "generated", { "A.ts": content("old"), "B.ts": content("old") }, verification);
  new Deployment(path.join(root, "initial-backup")).apply(target.plan());
  const next = new ProjectTarget("server", root, "generated", { "A.ts": content("new"), "B.ts": content("new") }, verification);
  const rename = fs.renameSync;
  let calls = 0;
  fs.renameSync = (...args) => { if (++calls === 2) throw new Error("simulated write failure"); return rename(...args); };
  try { assert.throws(() => new Deployment(path.join(root, "failed-backup")).apply(next.plan()), /simulated/); }
  finally { fs.renameSync = rename; }
  assert.deepEqual(fs.readFileSync(path.join(root, "generated/A.ts")), content("old"));
  assert.deepEqual(fs.readFileSync(path.join(root, "generated/B.ts")), content("old"));
  assert.equal(fs.existsSync(path.join(root, "failed-backup/restore.json")), true);
}));

test("경로 탈출과 잘못된 Unity 대상은 거부하고 생성 어셈블리는 비활성으로 배포한다", () => fixture(root => {
  assert.throws(() => checkPath(root, "../outside"));
  assert.throws(() => new UnityTarget(root, {}, verification), /Unity 프로젝트/);
  fs.mkdirSync(path.join(root, "ProjectSettings"));
  fs.writeFileSync(path.join(root, "ProjectSettings/ProjectVersion.txt"), "m_EditorVersion: 6000.2.8f1");
  const target = new UnityTarget(root, { "Test.cs": content("new") }, verification);
  const assembly = target.plan().find(write => write.destination.endsWith(".asmdef"));
  assert.deepEqual(JSON.parse(assembly.content).defineConstraints, ["ESCAPE_PROTOBUF_RUNTIME"]);
}));
