const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");

const hash = buffer => crypto.createHash("sha256").update(buffer).digest("hex");
const currentHash = file => fs.existsSync(file) ? hash(fs.readFileSync(file)) : null;
// Git on Windows may rewrite LF to CRLF. Accept only that representation change;
// deployment concurrency guards still compare the exact original bytes.
const ownsText = (file, expected) => {
  const lf = fs.readFileSync(file, "utf8").replaceAll("\r\n", "\n");
  return hash(Buffer.from(lf)) === expected || hash(Buffer.from(lf.replaceAll("\n", "\r\n"))) === expected;
};

function checkPath(root, relative) {
  if (path.isAbsolute(relative) || relative.split(/[\\/]/).some(part => part === ".." || part === ""))
    throw new Error("배포 경로가 유효하지 않습니다.");
  let cursor = root;
  for (const segment of relative.split(/[\\/]/)) {
    cursor = path.join(cursor, segment);
    try {
      if (fs.lstatSync(cursor).isSymbolicLink())
        throw new Error(`심볼릭 링크 배포 경로를 허용하지 않습니다: ${cursor}`);
    } catch (error) { if (error.code !== "ENOENT") throw error; }
  }
  return cursor;
}

class ProjectTarget {
  constructor(name, projectRoot, output, files, verification) {
    this.name = name;
    this.root = fs.realpathSync(projectRoot);
    this.output = output;
    this.files = files;
    this.verification = verification;
  }

  plan() {
    const manifestRelative = `${this.output}/protocol.manifest.json`;
    const manifestPath = checkPath(this.root, manifestRelative);
    const previous = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, "utf8")) : null;
    if (previous && (previous.owner !== "escape-protocol-tool" || previous.target !== this.name))
      throw new Error("다른 도구의 배포 기록입니다.");
    const nextNames = Object.keys(this.files);
    for (const oldName of Object.keys(previous?.files ?? {})) {
      checkPath(this.root, `${this.output}/${oldName}`);
      if (!nextNames.includes(oldName))
        throw new Error(`폐기된 생성 파일이 있습니다. 수동 검토 후 제거하세요: ${oldName}`);
    }
    const writes = [];
    const hashes = {};
    for (const [name, content] of Object.entries(this.files)) {
      const relative = `${this.output}/${name}`;
      const destination = checkPath(this.root, relative);
      const existing = currentHash(destination);
      const nextHash = hash(content);
      const oldHash = previous?.files?.[name];
      if (existing !== null && existing !== nextHash) {
        if (oldHash && oldHash !== existing && !ownsText(destination, oldHash))
          throw new Error(`생성 파일의 수동 변경을 발견했습니다: ${destination}`);
        if (!oldHash && !/^\/\/ (Code generated by protoc|<auto-generated>)/.test(fs.readFileSync(destination, "utf8")))
          throw new Error(`관리하지 않는 파일을 덮어쓸 수 없습니다: ${destination}`);
      }
      hashes[name] = nextHash;
      writes.push({ destination, root: this.root, relative, before: existing, content, changed: existing !== nextHash });
    }
    const manifest = { owner: "escape-protocol-tool", target: this.name,
      contractHash: this.verification.contractHash, fingerprint: this.verification.fingerprint,
      tools: this.verification.tools, files: hashes };
    const content = Buffer.from(JSON.stringify(manifest, null, 2) + "\n");
    writes.push({ destination: manifestPath, root: this.root, relative: manifestRelative,
      before: currentHash(manifestPath), content, changed: currentHash(manifestPath) !== hash(content) });
    return writes;
  }
}

class ServerTarget extends ProjectTarget {
  constructor(root, files, verification) {
    const packageJson = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
    if (!fs.existsSync(path.join(root, "tsconfig.json")) || !packageJson.dependencies?.["@bufbuild/protobuf"])
      throw new Error("서버 대상에 tsconfig.json과 @bufbuild/protobuf 의존성이 필요합니다.");
    super("server", root, "src/generated", files, verification);
  }
}

class UnityTarget extends ProjectTarget {
  constructor(root, files, verification) {
    if (!fs.existsSync(path.join(root, "ProjectSettings/ProjectVersion.txt")))
      throw new Error("클라이언트 대상이 Unity 프로젝트가 아닙니다.");
    const assembly = {
      name: "EscapeGame.Protocol.Generated", rootNamespace: "EscapeGame.Protocol.V1",
      references: [], includePlatforms: [], excludePlatforms: [], allowUnsafeCode: false,
      overrideReferences: false, precompiledReferences: [], autoReferenced: true,
      defineConstraints: ["ESCAPE_PROTOBUF_RUNTIME"], versionDefines: [], noEngineReferences: true
    };
    super("client", root, "Assets/3.Script/Generated/Protocol", {
      ...files, "EscapeGame.Protocol.Generated.asmdef": Buffer.from(JSON.stringify(assembly, null, 2) + "\n")
    }, verification);
  }
}

class Deployment {
  constructor(backupRoot) { this.backupRoot = backupRoot; }

  apply(writes) {
    const changed = writes.filter(write => write.changed);
    if (new Set(writes.map(write => write.destination)).size !== writes.length)
      throw new Error("배포 대상 경로가 중복됩니다.");
    for (const write of writes) {
      checkPath(write.root, write.relative);
      if (currentHash(write.destination) !== write.before)
        throw new Error(`계획 이후 변경을 발견했습니다: ${write.destination}`);
    }
    if (!changed.length) return;
    fs.mkdirSync(this.backupRoot, { recursive: true });
    const backupRecords = changed.map((write, index) => {
      const previous = write.before === null ? null : fs.readFileSync(write.destination);
      if (previous) fs.writeFileSync(path.join(this.backupRoot, `${index}.bak`), previous);
      return { ...write, previous };
    });
    fs.writeFileSync(path.join(this.backupRoot, "restore.json"), JSON.stringify(backupRecords.map((write, index) => ({
      destination: write.destination, backup: write.previous ? `${index}.bak` : null, previousHash: write.before
    })), null, 2));
    const completed = [];
    try {
      for (const write of backupRecords) {
        checkPath(write.root, write.relative);
        if (currentHash(write.destination) !== write.before) throw new Error("배포 중 동시 변경을 발견했습니다.");
        fs.mkdirSync(path.dirname(write.destination), { recursive: true });
        const temp = write.destination + "." + crypto.randomUUID() + ".pending";
        fs.writeFileSync(temp, write.content);
        try { fs.renameSync(temp, write.destination); }
        finally { if (fs.existsSync(temp)) fs.unlinkSync(temp); }
        completed.push(write);
      }
    } catch (error) {
      for (const write of completed.reverse()) {
        // 외부 편집까지 되돌리지 않도록 실제 적용한 내용이 남아 있는지 확인합니다.
        if (currentHash(write.destination) !== hash(write.content)) continue;
        if (write.previous) fs.writeFileSync(write.destination, write.previous);
        else fs.unlinkSync(write.destination);
      }
      throw error;
    }
  }
}

module.exports = { ProjectTarget, ServerTarget, UnityTarget, Deployment, hash, checkPath };
