const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');

// OpenAPI owns HTTP bindings. Protobuf owns messages; no duplicated JSON DTO generation.
function generateHttpApi(tsOutput, csOutput) {
  const spec = JSON.parse(fs.readFileSync(path.join(root, 'protocol/http/openapi.json'), 'utf8'));
  if (spec.openapi !== '3.0.3') throw new Error('OpenAPI 3.0.3 계약이 필요합니다.');
  const messages = new Set(fs.readdirSync(csOutput).filter(name => name.endsWith('.cs')).flatMap(name =>
    [...fs.readFileSync(path.join(csOutput, name), 'utf8').matchAll(/public sealed partial class ([A-Za-z][A-Za-z0-9_]*)/g)].map(match => match[1])));
  const outcomes = new Set([...fs.readFileSync(path.join(tsOutput, 'escape/v1/game_api.ts'), 'utf8').matchAll(/\$case: "([A-Za-z][A-Za-z0-9]*)"/g)].map(match => match[1]));
  const operations = [];
  const names = new Set();
  for (const [route, methods] of Object.entries(spec.paths)) for (const [method, operation] of Object.entries(methods)) {
    // 상태 확인·계약 조회는 Swagger에 표시하되 Protobuf 게임 호출 코드는 생성하지 않습니다.
    if (operation['x-codegen-exclude'] === true) continue;
    const name = operation.operationId;
    if (!/^[A-Z][A-Za-z0-9]*$/.test(name) || names.has(name) || !['get', 'post'].includes(method)) throw new Error('유효하지 않은 HTTP 작업: ' + name);
    names.add(name);
    const outcome = operation['x-protobuf-outcome'];
    if (!outcomes.has(outcome) || outcome === 'failure') throw new Error('Protobuf 성공 응답 분기가 없습니다: ' + name);
    const parameters = operation.parameters ?? [];
    for (const parameter of parameters) if (parameter.in !== 'path' || !['sessionId', 'puzzleId'].includes(parameter.name) || !route.includes('{' + parameter.name + '}')) throw new Error('지원하지 않는 경로 변수입니다.');
    const request = operation['x-protobuf-request'];
    if (request && !messages.has(request)) throw new Error('생성된 Protobuf 요청 타입이 없습니다: ' + request);
    const successStatus = operation['x-success-status'];
    if (![200, 201].includes(successStatus) || !operation.responses[successStatus]?.content?.['application/protobuf']) throw new Error('성공 응답 계약이 유효하지 않습니다.');
    operations.push({ name, method: method.toUpperCase(), path: route, outcome, successStatus, request, heartbeat: !!operation['x-heartbeat-timeout'], parameters });
  }
  const header = '// <auto-generated> OpenAPI HTTP bindings. DO NOT EDIT. </auto-generated>\n';
  fs.mkdirSync(path.join(tsOutput, 'http'), { recursive: true });
  fs.writeFileSync(path.join(tsOutput, 'http/game-api.ts'), header + 'export const gameApiOpenApi = ' + JSON.stringify(spec, null, 2) + ' as const;\nexport const gameApiOperations = ' + JSON.stringify(operations.map(({ parameters, ...op }) => op), null, 2) + ' as const;\n');
  const parameterList = op => op.parameters.map(p => (p.name === 'puzzleId' ? 'int ' : 'string ') + p.name);
  const argumentsList = op => op.parameters.map(p => p.name);
  const authenticated = op => op.parameters.some(p => p.name === 'sessionId');
  const methodParameters = op => [...parameterList(op), ...(authenticated(op) ? ['string participantToken'] : []), ...(op.request ? [op.request + ' request'] : []), 'CancellationToken token'];
  const lines = [header, 'using System;', 'using System.Threading;', 'using System.Threading.Tasks;', 'using Google.Protobuf;', 'namespace EscapeGame.Protocol.V1 {',
    'public sealed class GameApiOperation {',
    ' public string Method { get; } public string Path { get; } public GameApiResponse.OutcomeOneofCase Outcome { get; } public int SuccessStatus { get; } public bool Heartbeat { get; }',
    ' public GameApiOperation(string method,string path,GameApiResponse.OutcomeOneofCase outcome,int status,bool heartbeat) { Method=method; Path=path; Outcome=outcome; SuccessStatus=status; Heartbeat=heartbeat; }', '}', 'public static class GameApiRoutes {'];
  for (const op of operations) {
    const uri = op.path.replace('{sessionId}', '{Uri.EscapeDataString(sessionId)}').replace('{puzzleId}', '{puzzleId}');
    lines.push(` public static GameApiOperation ${op.name}(${parameterList(op).join(',')}) => new GameApiOperation("${op.method}",$"${uri}",GameApiResponse.OutcomeOneofCase.${op.outcome[0].toUpperCase() + op.outcome.slice(1)},${op.successStatus},${op.heartbeat});`);
  }
  lines.push('}', 'public interface IGameApi {');
  for (const op of operations) lines.push(` Task<GameApiResponse> ${op.name}Async(${methodParameters(op).join(',')});`);
  lines.push('}', 'public abstract class GameApiClientBase : IGameApi {', ' protected abstract Task<GameApiResponse> SendAsync(GameApiOperation operation,IMessage request,string participantToken,CancellationToken token);');
  for (const op of operations) lines.push(` public Task<GameApiResponse> ${op.name}Async(${methodParameters(op).join(',')}) => SendAsync(GameApiRoutes.${op.name}(${argumentsList(op).join(',')}),${op.request ? 'request' : 'null'},${authenticated(op) ? 'participantToken' : 'null'},token);`);
  lines.push('}', '}');
  fs.mkdirSync(csOutput, { recursive: true });
  fs.writeFileSync(path.join(csOutput, 'HttpApi.cs'), lines.join('\n') + '\n');
}
module.exports = { generateHttpApi };
